import {test,expect} from '@playwright/test'

test('The evaluation bar follows the live game and can be hidden from the board settings',async({page,request})=>{
  let game=await(await request.post('/api/games',{data:{color:'w',elo:1500}})).json()
  for(const move of ['e2e4','e7e5','d1h5','b8c6'])game=await(await request.post(`/api/games/${game.id}/moves`,{data:{move,version:game.version,revision:game.revision,actor:game.turn==='w'?'human':'maia'}})).json()
  await page.addInitScript(id=>localStorage.setItem('chess-coach-game',id),game.id)
  await page.goto('/')
  await page.getByRole('button',{name:'Continua partita',exact:true}).click()
  const bar=page.locator('.stockfish-bar')
  await expect(bar).toHaveAttribute('aria-label',/Valutazione Stockfish [+-]\d/,{timeout:30000})
  const boardBox=await page.locator('.board-stage').boundingBox(),barBox=await bar.boundingBox()
  expect(barBox!.x).toBeLessThan(boardBox!.x+30)
  await page.screenshot({path:'test-results/eval-bar.png'})
  await page.getByRole('button',{name:/^\W*Scacchiera$/}).click()
  await page.getByRole('checkbox',{name:'Barra di valutazione'}).uncheck()
  await expect(bar).toHaveCount(0)
})

test('The Maia bar shows the expected score for two humans of the game level and can be hidden',async({page,request})=>{
  let game=await(await request.post('/api/games',{data:{color:'w',elo:1500}})).json()
  for(const move of ['e2e4','e7e5','d1h5','b8c6'])game=await(await request.post(`/api/games/${game.id}/moves`,{data:{move,version:game.version,revision:game.revision,actor:game.turn==='w'?'human':'maia'}})).json()
  await page.addInitScript(id=>localStorage.setItem('chess-coach-game',id),game.id)
  await page.goto('/')
  await page.getByRole('button',{name:'Continua partita',exact:true}).click()
  const bar=page.locator('.maia-bar')
  await expect(bar).toHaveAttribute('aria-label',/Maia 1500: punteggio atteso del Bianco \d+% \(vince il Bianco \d+%, patta \d+%, vince il Nero \d+%\)/,{timeout:90000})
  const stockfish=await page.locator('.stockfish-bar').boundingBox(),maiaBox=await bar.boundingBox(),board=await page.locator('.board').boundingBox()
  // Stockfish on the left of the board, Maia on the right.
  expect(stockfish!.x+stockfish!.width).toBeLessThanOrEqual(board!.x)
  expect(maiaBox!.x).toBeGreaterThanOrEqual(board!.x+board!.width)
  expect(Math.abs(maiaBox!.height-board!.height)).toBeLessThan(2)
  const label=await bar.getAttribute('aria-label')
  const [score,win,draw,loss]=label!.match(/\d+(?=%)/g)!.map(Number)
  expect(Math.abs(win+draw+loss-100)).toBeLessThanOrEqual(2)
  expect(Math.abs(win+draw/2-score)).toBeLessThanOrEqual(1)
  await page.screenshot({path:'test-results/maia-bar.png'})
  await page.getByRole('button',{name:/^\W*Scacchiera$/}).click()
  await page.getByRole('checkbox',{name:'Barra Maia (punteggio umano)'}).uncheck()
  await expect(bar).toHaveCount(0)
  await expect(page.locator('.stockfish-bar')).toHaveCount(1)
})
