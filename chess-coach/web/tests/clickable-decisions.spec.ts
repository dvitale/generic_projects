import {test,expect} from '@playwright/test'

test('decision tile opens all mistakes, filters them and navigates to the selected position',async({page,request})=>{
  const game=await(await request.post('/api/import',{data:{pgn:'1. e4 e5 2. Nf3 Nc6 3. Bb5 a6 4. Ba4 Nf6 *'}})).json()
  const job=await(await request.post(`/api/games/${game.id}/analysis`)).json()
  await expect.poll(async()=> (await(await request.get('/api/jobs/'+job.jobId)).json()).status).toBe('complete')
  const flagged=[{ply:0,san:'e4',moveNumber:1,color:'w',kind:'inaccuracy',lossCp:80},{ply:2,san:'Nf3',moveNumber:2,color:'w',kind:'error',lossCp:180},{ply:4,san:'Bb5',moveNumber:3,color:'w',kind:'inaccuracy',lossCp:179},{ply:6,san:'Ba4',moveNumber:4,color:'w',kind:'error',lossCp:null}]
  await page.route(`**/api/games/${game.id}/decision-quality`,route=>route.fulfill({json:{ready:true,decisions:4,sound:0,errors:2,inaccuracies:2,advantages:0,maintained:0,moments:[],flagged}}))
  await page.addInitScript(id=>localStorage.setItem('chess-coach-game',id),game.id)
  await page.goto('/')
  const quality=page.getByRole('region',{name:'Qualità delle decisioni'})
  const toggle=quality.getByRole('button',{name:/errori rilevanti · 2 imprecisioni/})
  await expect(toggle).toHaveAttribute('aria-expanded','false')
  await toggle.focus();await toggle.press('Enter')
  const list=quality.getByRole('region',{name:'Mosse da rivedere'})
  await expect(list.getByRole('listitem')).toHaveCount(4)
  await list.getByRole('button',{name:'Imprecisioni (2)',exact:true}).click()
  await expect(list.getByRole('listitem')).toHaveCount(2)
  await expect(list).toContainText('1. e4');await expect(list).toContainText('3. Bb5')
  await list.getByRole('button',{name:'Errori rilevanti (2)',exact:true}).click()
  await expect(list.getByRole('listitem')).toHaveCount(2)
  await expect(list).toContainText('Confronto con matto');await expect(list).not.toContainText('999.99')
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await toggle.click();await expect(list).toBeHidden();await toggle.click()
  await list.getByRole('button',{name:/4\. Ba4/}).click()
  await expect(page.getByRole('tab',{name:'Mosse',exact:true})).toHaveAttribute('aria-selected','true')
  await expect(page.getByRole('combobox',{name:'Mossa da confrontare'})).toHaveValue('6')
})
