import {test,expect,type Page} from '@playwright/test'

// Queen attacked by ...g6: Qd1, Qf3 and Qe2 keep the game, Qh3 runs into ...d5.
const QUEEN='r1bqkbnr/pppp1p1p/2n3p1/4p2Q/2B1P3/8/PPPP1PPP/RNB1K1NR w KQkq - 0 4'
async function boardMove(page:Page,move:string){await page.locator(`[data-square="${move.slice(0,2)}"]`).click();await page.locator(`[data-square="${move.slice(2,4)}"]`).click()}

test('Live: mark without help, then a guided search on a separate board with progressive hints',async({page,request})=>{
  const game=await(await request.post('/api/games',{data:{color:'w',fen:QUEEN}})).json()
  await page.addInitScript(id=>localStorage.setItem('chess-coach-game',id),game.id)
  await page.goto('/')
  await page.getByRole('button',{name:'Continua partita',exact:true}).click()
  const stuck=page.getByRole('button',{name:'Qui mi sento bloccato'})
  await stuck.click()
  await page.getByRole('button',{name:/Segna e continua/}).click()
  await expect(page.getByRole('status').filter({hasText:'Momento segnato senza aiuti'})).toBeVisible()
  await expect(page.locator('.alternative-hint')).toHaveCount(0)
  let saved=await(await request.get('/api/games/'+game.id)).json()
  expect(saved.moves).toEqual([]);expect(saved.assistedPlies).toEqual([])

  await stuck.click()
  await page.getByRole('button',{name:/Aiutami a ragionare/}).click()
  const questions=page.getByRole('region',{name:'Prima della ricerca'})
  await expect(questions).toContainText('Che cosa temi che possa fare l’avversario?')
  await expect(page.getByRole('button',{name:'Inizia la ricerca'})).toBeDisabled()
  await expect(page.locator('.alternative-hint')).toHaveCount(0)
  await questions.getByRole('group',{name:'Che cosa temi che possa fare l’avversario?'}).getByRole('button',{name:'Indica sulla scacchiera'}).click()
  await boardMove(page,'g6h5')
  await expect(questions).toContainText('Temi gxh5')
  await questions.getByRole('group',{name:'Quali mosse hai considerato?'}).getByRole('button',{name:'Indica sulla scacchiera'}).click()
  await boardMove(page,'h5h3')
  await expect(questions.getByRole('button',{name:'Togli Qh3'})).toBeVisible()
  await questions.getByRole('button',{name:'Fatto'}).click()
  await page.getByRole('button',{name:'Inizia la ricerca'}).click()

  const search=page.getByRole('region',{name:'Ricerca'})
  await expect(search.getByRole('heading',{name:'Ricerca autonoma'})).toBeVisible({timeout:30000})
  // No evaluation, arrow or engine choice before help is asked for.
  await expect(page.locator('.alternative-hint')).toHaveCount(0)
  await expect(page.locator('.analysis-arrow')).toHaveCount(0)
  await expect(search).not.toContainText(/[+−-]\d,\d\d/)
  await boardMove(page,'h5h3')
  await expect(search.getByRole('status')).toContainText('Non risolve il problema',{timeout:30000})
  await expect(page.locator('.alternative-hint')).toHaveCount(0)
  await search.getByRole('button',{name:'Chiedi un aiuto: domanda sulla minaccia'}).click()
  await expect(page.locator('.alternative-hint')).toHaveCount(1)
  await expect(page.locator('.alternative-hint')).toContainText('gxh5')
  await expect(page.getByRole('img',{name:'Aiuto ricevuto: livello 1 di 5'})).toBeVisible()
  await boardMove(page,'h5d1')
  const solution=page.getByRole('region',{name:'Soluzione',exact:true})
  await expect(solution).toContainText('ALTERNATIVA TROVATA',{timeout:30000})
  await expect(solution).toContainText('Che cosa temevi')
  await page.screenshot({path:'test-results/find-alternative-live.png',fullPage:true})
  const after=page.getByRole('region',{name:'Dopo la soluzione'})
  await after.getByRole('button',{name:'Non mi era venuta in mente'}).click()
  await after.getByRole('button',{name:'Ho notato una risorsa di un pezzo'}).click()
  await after.getByRole('button',{name:'Salva e programma il ripasso'}).click()
  await expect(page.getByRole('region',{name:'Esito'})).toContainText('Risolto con indizio')
  await expect(page.getByRole('region',{name:'Esito'})).toContainText('Ripetizione')
  // The exercise never touched the game: only the decision is marked as assisted, because a hint was shown live.
  saved=await(await request.get('/api/games/'+game.id)).json()
  expect(saved.moves).toEqual([]);expect(saved.assistedPlies).toEqual([0]);expect(saved.pgn).toBe(game.pgn)
  await page.getByRole('button',{name:'Gioca Qd1 nella partita'}).click()
  await expect(page.getByRole('button',{name:'Qui mi sento bloccato'})).toBeVisible()
  await expect.poll(async()=>(await(await request.get('/api/games/'+game.id)).json()).moves[0]).toBe('h5d1')
})

test('Review: a recollected episode survives a reload and works on a small screen',async({page,request})=>{
  let game=await(await request.post('/api/games',{data:{color:'w',fen:QUEEN}})).json()
  game=await(await request.post(`/api/games/${game.id}/moves`,{data:{move:'h5e2',version:0,revision:0,actor:'human'}})).json()
  const pgn=await(await request.get(`/api/games/${game.id}/pgn`)).text()
  await page.setViewportSize({width:390,height:844})
  await page.addInitScript(id=>localStorage.setItem('chess-coach-game',id),game.id)
  await page.goto('/')
  await page.getByRole('button',{name:'Posizione iniziale'}).click()
  await page.getByRole('button',{name:'Qui mi sentivo bloccato'}).click()
  await page.getByRole('button',{name:/Aiutami a ragionare/}).click()
  const questions=page.getByRole('region',{name:'Prima della ricerca'})
  await questions.getByRole('group',{name:'Che cosa temi che possa fare l’avversario?'}).getByRole('button',{name:'Non ne vedo nessuna'}).click()
  await questions.getByRole('group',{name:'Quali mosse hai considerato?'}).getByRole('button',{name:'Non ne vedo nessuna'}).click()
  await page.getByRole('button',{name:'Inizia la ricerca'}).click()
  await expect(page.getByRole('region',{name:'Ricerca'})).toBeVisible({timeout:30000})
  await expect(page.getByRole('region',{name:'Esercizio'})).toContainText('risposte ricostruite dopo')

  await page.goto('/?section=alternative')
  await page.getByRole('button',{name:/Momento originale · Ricerca in corso/}).click()
  const search=page.getByRole('region',{name:'Ricerca'})
  await expect(search.getByRole('heading',{name:'Ricerca autonoma'})).toBeVisible()
  await expect(page.locator('[data-square="h5"]')).toBeVisible()
  const help=search.getByRole('button',{name:'Chiedi un aiuto: domanda sulla minaccia'})
  await help.scrollIntoViewIfNeeded();await help.click()
  await expect(page.locator('.alternative-hint')).toHaveCount(1)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:'test-results/find-alternative-mobile.png',fullPage:true})
  expect(await(await request.get(`/api/games/${game.id}/pgn`)).text()).toBe(pgn)
  expect((await(await request.get('/api/games/'+game.id)).json()).assistedPlies).toEqual([])
})

