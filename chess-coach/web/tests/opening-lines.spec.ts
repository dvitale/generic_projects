test('A drill as on Maia Chess: line on the board, target, extend, end and the drill review',async({page,request})=>{
  async function decide(){
    await expect(page.getByText(/Maia 1500 · Tocca a te/)).toBeVisible({timeout:60000})
    const id=await page.evaluate(()=>localStorage.getItem('chess-coach-drill'))
    const g=await(await request.get('/api/games/'+id)).json()
    const response=page.waitForResponse(r=>r.url().endsWith('/moves')&&r.request().method()==='POST')
    await page.locator(`[data-square="${g.legalMoves[0].slice(0,2)}"]`).click();await page.locator(`[data-square="${g.legalMoves[0].slice(2,4)}"]`).click()
    await response
  }
  await page.goto('/?section=drill')
  await expect(page.getByLabel('Durata drill')).toHaveValue('10')
  await page.getByLabel('Durata drill').selectOption('3')
  await page.getByLabel('Linea di Partita italiana').selectOption('italiana:fried-liver')
  await page.getByRole('button',{name:'Avvia Partita italiana contro Maia'}).click()
  await expect(page.getByText('Partita italiana: Two Knights Defense, Fried Liver Attack',{exact:true})).toBeVisible()
  for(let i=0;i<3;i++)await decide()
  await expect(page.getByText('Traguardo raggiunto (3/3 mosse).')).toBeVisible()
  await page.getByRole('button',{name:'Prolunga il drill'}).click()
  await expect(page.getByText('3 decisioni · senza limite')).toBeVisible()
  await decide()
  await expect(page.getByText('4 decisioni · senza limite')).toBeVisible()
  await expect(page.getByText(/Maia 1500 · Tocca a te/)).toBeVisible({timeout:60000})
  await page.getByRole('button',{name:'Termina e valuta',exact:true}).click()
  await expect(page.getByText('VALUTAZIONE DEL DRILL')).toBeVisible()
  await expect(page.getByText('Andamento della valutazione')).toBeVisible({timeout:90000})
  await expect(page.getByText('Precisione',{exact:true})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Decisioni critiche'})).toBeVisible()
  await expect(page.getByText(/Servono almeno 10 tue decisioni non obbligate per il confronto: qui sono 4/)).toBeVisible({timeout:30000})
  await page.getByRole('button',{name:'Inizio del drill'}).click()
  await expect(page.getByText('Fine della linea: da qui il drill.')).toBeVisible()
  await page.getByRole('button',{name:'Mossa successiva'}).click()
  await expect(page.getByText('Dopo la semimossa 1 del drill.')).toBeVisible()
  await page.screenshot({path:'test-results/drill-review.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'test-results/drill-review-mobile.png',fullPage:true})
  await page.setViewportSize({width:1280,height:900})
  await page.getByRole('button',{name:'Rigioca la stessa linea →'}).click()
  await expect(page.getByText('Partita italiana: Two Knights Defense, Fried Liver Attack',{exact:true})).toBeVisible()
  await expect(page.getByText('0 / 3 decisioni')).toBeVisible()
})
